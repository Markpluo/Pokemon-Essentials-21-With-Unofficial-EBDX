export function goal(f: FlagReader): string | null {
  if (!f('mumTalked')) return null;
  let next = STEPS.length;
  while (next > 0 && !f(STEPS[next - 1][0])) next--;
  return next < STEPS.length ? STEPS[next][1] : 'The story continues in Chapter 11.';
}
